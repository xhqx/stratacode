def get_points(d_str):
    tokens = re.findall(r'[A-Za-z]+|-?\d+\.?\d*', d_str)
    points = []
    
    current_cmd = ''
    i = 0
    cur_x = 0
    cur_y = 0
    while i < len(tokens):
        t = tokens[i]
        if t.isalpha():
            current_cmd = t
            i += 1
        else:
            if current_cmd in ['M', 'L', 'C', 'c', 'm', 'l']:
                # pairs of x, y
                x = float(tokens[i])
                y = float(tokens[i+1])
                i += 2
                
                if current_cmd.islower():
                    cur_x += x
                    cur_y += y
                else:
                    cur_x = x
                    cur_y = y
                points.append((cur_x, cur_y))
            elif current_cmd == 'z' or current_cmd == 'Z':
                pass
            else:
                break
    return points

