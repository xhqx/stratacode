def transform_path(d_str, scale, offset_x, offset_y):
    tokens = re.findall(r'[A-Za-z]+|-?\d+\.?\d*', d_str)
    new_tokens = []
    current_cmd = ''
    i = 0
    while i < len(tokens):
        t = tokens[i]
        if t.isalpha():
            current_cmd = t
            new_tokens.append(t)
            i += 1
        else:
            if current_cmd in ['M', 'L', 'C', 'c', 'm', 'l']:
                x = float(tokens[i])
                y = float(tokens[i+1])
                i += 2
                
                if current_cmd.islower():
                    # relative values just scale, don't offset
                    nx = x * scale
                    ny = y * scale
                else:
                    # absolute values
                    nx = x * scale + offset_x
                    ny = y * scale + offset_y
                    
                new_tokens.append(f"{nx:.2f}")
                new_tokens.append(f"{ny:.2f}")
            elif current_cmd == 'z' or current_cmd == 'Z':
                pass

    return ' '.join(new_tokens)

